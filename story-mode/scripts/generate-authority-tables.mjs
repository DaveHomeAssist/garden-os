#!/usr/bin/env node
// Regenerates the pure-data authority mirrors from the canonical specs.
//
//   node scripts/generate-authority-tables.mjs          write the files
//   node scripts/generate-authority-tables.mjs --check  exit 1 if they are stale
//
// Both authority runtimes (the Node service and the fetch-compatible worker)
// import these modules directly, so they must stay plain JS with no Vite
// aliases or JSON imports. The drift tests in src/server/*.test.js fail the
// suite when a spec edit is not regenerated here.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const storyModeDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(storyModeDir, '..');

function readSpec(name) {
  return JSON.parse(readFileSync(resolve(repoRoot, 'specs', name), 'utf8'));
}

const IDENTIFIER_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function formatKey(key) {
  return IDENTIFIER_RE.test(key) ? key : `'${key.replace(/'/g, "\\'")}'`;
}

function formatScalar(value) {
  if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  if (value === null) return 'null';
  return String(value);
}

function isInline(value) {
  if (Array.isArray(value)) return value.every((entry) => entry === null || typeof entry !== 'object');
  if (value && typeof value === 'object') {
    return Object.values(value).every((entry) => entry === null || typeof entry !== 'object');
  }
  return true;
}

function toJs(value, depth = 0) {
  const pad = '  '.repeat(depth + 1);
  const closePad = '  '.repeat(depth);
  if (Array.isArray(value)) {
    if (!value.length) return '[]';
    if (isInline(value)) return `[${value.map((entry) => formatScalar(entry)).join(', ')}]`;
    if (value.every((entry) => entry && typeof entry === 'object' && !Array.isArray(entry) && isInline(entry))) {
      return `[\n${value.map((entry) => `${pad}${toJs(entry, depth + 1)},`).join('\n')}\n${closePad}]`;
    }
    return `[\n${value.map((entry) => `${pad}${toJs(entry, depth + 1)},`).join('\n')}\n${closePad}]`;
  }
  if (value && typeof value === 'object') {
    const entries = Object.entries(value).filter(([, entry]) => entry !== undefined);
    if (!entries.length) return '{}';
    if (isInline(value) && depth > 0) {
      return `{ ${entries.map(([key, entry]) => `${formatKey(key)}: ${formatScalar(entry)}`).join(', ')} }`;
    }
    return `{\n${entries.map(([key, entry]) => `${pad}${formatKey(key)}: ${toJs(entry, depth + 1)},`).join('\n')}\n${closePad}}`;
  }
  return formatScalar(value);
}

function normalizeRewards(rewards) {
  return (rewards ?? []).map((reward) => ({
    amount: reward.amount ?? 1,
    id: reward.id,
    type: reward.type,
  }));
}

async function buildRewardTables() {
  const questDeck = readSpec('QUEST_DECK.json');
  const cropData = readSpec('CROP_SCORING_DATA.json');
  const festivalsModule = await import(pathToFileURL(resolve(storyModeDir, 'src/data/festivals-data.js')).href);
  const { ACTIVITY_REWARD_TABLE, FESTIVALS } = festivalsModule;

  const questRewards = {};
  for (const quest of questDeck.quests ?? []) {
    const outcomes = {};
    for (const outcome of quest.outcomes ?? []) {
      outcomes[outcome.id] = normalizeRewards(outcome.rewards);
    }
    questRewards[quest.id] = {
      outcomes,
      rewards: normalizeRewards(quest.rewards),
    };
  }

  const activityRewards = {};
  for (const [rewardType, rewards] of Object.entries(ACTIVITY_REWARD_TABLE)) {
    activityRewards[rewardType] = normalizeRewards(rewards);
  }

  const festivals = {};
  for (const [festivalId, festival] of Object.entries(FESTIVALS)) {
    festivals[festivalId] = {
      activities: Object.fromEntries(festival.activities.map((activity) => [activity.id, activity.rewardType])),
    };
  }

  const recipes = {};
  for (const [recipeId, recipe] of Object.entries(cropData.recipes ?? {})) {
    recipes[recipeId] = [...recipe.crops];
  }

  return `// Canonical server-owned reward tables for the Story Mode authority runtimes.
// GENERATED by scripts/generate-authority-tables.mjs from specs/QUEST_DECK.json,
// specs/CROP_SCORING_DATA.json, and src/data/festivals-data.js. Do not hand edit.
// Pure data, no imports: both the Node authority service and the fetch-compatible
// worker load this module, so it must stay free of Vite aliases, JSON imports,
// and runtime-specific APIs.

const AUTHORITY_QUEST_REWARDS = ${toJs(questRewards)};

const AUTHORITY_FESTIVAL_ACTIVITY_REWARDS = ${toJs(activityRewards)};

const AUTHORITY_FESTIVALS = ${toJs(festivals)};

const AUTHORITY_RECIPE_TABLE = ${toJs(recipes)};

export {
  AUTHORITY_FESTIVAL_ACTIVITY_REWARDS,
  AUTHORITY_FESTIVALS,
  AUTHORITY_QUEST_REWARDS,
  AUTHORITY_RECIPE_TABLE,
};
`;
}

function buildMarketTables() {
  const market = readSpec('MARKET_PRICES.json');
  const items = {};
  for (const [itemId, item] of Object.entries(market.items ?? {})) {
    items[itemId] = {
      basePrice: item.basePrice,
      label: item.label ?? itemId,
      seasonMultipliers: { ...(item.seasonMultipliers ?? {}) },
      type: item.type ?? 'material',
    };
  }
  return `// Canonical market price table for the Story Mode authority runtimes.
// GENERATED by scripts/generate-authority-tables.mjs from specs/MARKET_PRICES.json.
// Do not hand edit. Pure data, no imports, so the Node service, the worker, and
// the client market math can all share one table.

const AUTHORITY_MARKET_SEED = ${formatScalar(market.seedDefault)};

const AUTHORITY_MARKET_STARTING_BALANCE = ${Number(market.currency?.startingBalance ?? 0)};

const AUTHORITY_MARKET_ITEMS = ${toJs(items)};

export {
  AUTHORITY_MARKET_ITEMS,
  AUTHORITY_MARKET_SEED,
  AUTHORITY_MARKET_STARTING_BALANCE,
};
`;
}

function buildCraftingTables() {
  const spec = readSpec('CRAFTING_RECIPES.json');
  const recipes = {};
  for (const recipe of spec.recipes ?? []) {
    recipes[recipe.id] = {
      materials: (recipe.materials ?? []).map((material) => ({ itemId: material.itemId, count: material.count })),
      output: {
        itemId: recipe.output?.itemId,
        count: recipe.output?.count ?? 1,
        durability: recipe.output?.durability ?? null,
      },
    };
  }
  return `// Canonical crafting recipe table for the Story Mode authority runtimes.
// GENERATED by scripts/generate-authority-tables.mjs from specs/CRAFTING_RECIPES.json.
// Do not hand edit. Pure data, no imports.

const AUTHORITY_CRAFTING_RECIPES = ${toJs(recipes)};

export {
  AUTHORITY_CRAFTING_RECIPES,
};
`;
}

function buildWorldTables() {
  const worldMap = readSpec('WORLD_MAP.json');
  const zones = {};
  for (const [zoneId, zone] of Object.entries(worldMap.zones ?? {})) {
    const gate = zone.gate ?? null;
    zones[zoneId] = {
      bedSlots: Number(zone.bedSlots ?? 0),
      gate: gate ? {
        type: gate.type,
        quest: gate.requirement?.quest ?? null,
        activeFestival: gate.requirement?.activeFestival === true,
        skill: gate.requirement?.skill ?? null,
        level: gate.requirement?.level ?? null,
        npc: gate.requirement?.npc ?? null,
        minValue: gate.requirement?.minValue ?? null,
      } : null,
    };
  }
  return `// Canonical zone table for the Story Mode authority runtimes.
// GENERATED by scripts/generate-authority-tables.mjs from specs/WORLD_MAP.json.
// Do not hand edit. Pure data, no imports.

const AUTHORITY_ZONES = ${toJs(zones)};

export {
  AUTHORITY_ZONES,
};
`;
}

const outputs = [
  ['src/server/authority-reward-tables.js', await buildRewardTables()],
  ['src/server/authority-market-tables.js', buildMarketTables()],
  ['src/server/authority-crafting-tables.js', buildCraftingTables()],
  ['src/server/authority-world-tables.js', buildWorldTables()],
];

const checkOnly = process.argv.includes('--check');
let stale = 0;
for (const [relativePath, contents] of outputs) {
  const target = resolve(storyModeDir, relativePath);
  let current = null;
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    current = null;
  }
  if (current === contents) continue;
  if (checkOnly) {
    stale += 1;
    console.error(`stale: ${relativePath}`);
  } else {
    writeFileSync(target, contents);
    console.log(`wrote ${relativePath}`);
  }
}
if (checkOnly && stale) process.exit(1);
